import { writeFileSync } from "node:fs";
import { KOREAN_CONTENT } from "../src/data/korean-content.js";

const quote = value => "'" + String(value).replace(/'/g, "''") + "'";
const groups = KOREAN_CONTENT.groups;
const sql = ["-- Generated by node scripts/generate-korean-seed.mjs. Run after 20261007_multilingual.sql.",
  "-- Inserts missing starter content only; never resets edits or learning progress.", "begin;",
  "insert into public.vocabulary_groups(id, title, language_code, sort_order) values\n" +
    groups.map((group, i) => `  (${quote(group.id)}, ${quote(group.n)}, 'ko', ${i})`).join(",\n") + "\non conflict(id) do nothing;",
  "insert into public.vocabulary_words(id, word, group_id, meaning, example, ipa, reading, romanization, cloze_text, cloze_answer, sort_order) values\n" +
    groups.flatMap(group => group.w.map((card, i) => {
      const meta = card[4];
      return "  (" + [meta.id, card[0], group.id, card[1], card[2], card[3], meta.reading, meta.romanization, meta.cloze_text, meta.cloze_answer].map(quote).join(", ") + `, ${i})`;
    })).join(",\n") + "\non conflict do nothing;", "commit;\n"];
writeFileSync(new URL("../supabase/korean-seed.sql", import.meta.url), sql.join("\n\n"));
console.log(`Generated Korean seed: ${groups.length} groups, ${groups.flatMap(group => group.w).length} cards.`);
